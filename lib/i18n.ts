export const DICTIONARIES: Record<Lang, Dict> = { en, es, hy, zh }

export function translate(lang: Lang, key: DictKey, vars?: Record<string, string | number>) {
  let s = DICTIONARIES[lang]?.[key] ?? en[key] ?? key
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v))
  return s
}

export function detectLanguage(candidates: readonly string[]): Lang {
  for (const c of candidates) {
    const code = c.toLowerCase()
    if (code.startsWith('es')) return 'es'
    if (code.startsWith('hy')) return 'hy'
    if (code.startsWith('zh')) return 'zh'
    if (code.startsWith('en')) return 'en'
  }
  return 'en'
}
